package org.magora.node

import java.time.Duration
import java.time.Instant
import java.time.LocalDate
import java.time.ZoneOffset
import kotlin.math.ceil

/**
 * Time-of-day fields for detection and ACI rows, ported from firmware detect.py at pin
 * f0c1940 (get_time_category, get_temporal_context, is_dawn_chorus) and the astral 3.2
 * sun() it calls (elevation-0 observer, tzinfo UTC, civil dawn/dusk).
 *
 * Quirks are kept on purpose so phone rows match Pi rows: detect.py strips the UTC tzinfo
 * and asks astral for the sun on the *UTC* date, and any astral failure (including the
 * "Unable to find a sunset time on the date specified" case near UTC midnight in the
 * western hemisphere) sends time_category to the UTC-hour fallback and the temporal
 * fields to null. Verified against vectors generated by real astral 3.2 in the unit tests.
 */
object Temporal {

    data class Context(
        val timeCategory: String,
        val minutesFromSunrise: Int?,
        val dawnChorusWindow: Boolean?,
        val phenologicalWeek: Int?,
        val season: String?,
    ) {
        /** detect.py: dawn = temporal["dawn_chorus_window"] or is_dawn_chorus(time_category). */
        val dawn: Boolean get() = dawnChorusWindow == true || timeCategory == "Dawn"
    }

    fun context(now: Instant, lat: Double, lon: Double): Context {
        val category = timeCategory(now, lat, lon)
        val sunrise = try {
            Astral.sun(LocalDate.ofInstant(now, ZoneOffset.UTC), lat, lon).sunrise
        } catch (_: Astral.SunError) {
            null
        }
        if (sunrise == null) return Context(category, null, null, null, null)
        val minutes = (micros(Duration.between(sunrise, now)).toDouble() / 1e6 / 60.0).toInt()
        val week = minOf(52, ceil(dayOfYear(now) / 7.0).toInt())
        return Context(category, minutes, minutes in -30..120, week, season(week))
    }

    fun timeCategory(now: Instant, lat: Double, lon: Double): String {
        val sun = try {
            Astral.sun(LocalDate.ofInstant(now, ZoneOffset.UTC), lat, lon)
        } catch (_: Astral.SunError) {
            return fallbackCategory(now.atOffset(ZoneOffset.UTC).hour)
        }
        val sunrise = sun.sunrise
        val sunset = sun.sunset
        val dawnStart = sunrise.minus(Duration.ofMinutes(30))
        val dawnEnd = sunrise.plus(Duration.ofMinutes(60))
        val duskStart = sunset.minus(Duration.ofMinutes(30))
        val duskEnd = sunset.plus(Duration.ofMinutes(60))
        val morningEnd = sunrise.plus(Duration.ofHours(4))
        val afternoonStart = sunset.minus(Duration.ofHours(2))
        return when {
            now >= dawnStart && now <= dawnEnd -> "Dawn"
            now > dawnEnd && now <= morningEnd -> "Morning"
            now > morningEnd && now <= afternoonStart -> "Midday"
            now > afternoonStart && now < duskStart -> "Afternoon"
            now >= duskStart && now <= duskEnd -> "Dusk"
            else -> "Night"
        }
    }

    private fun fallbackCategory(hour: Int): String = when {
        hour in 5 until 9 -> "Dawn"
        hour in 9 until 12 -> "Morning"
        hour in 12 until 16 -> "Midday"
        hour in 16 until 19 -> "Afternoon"
        hour in 19 until 21 -> "Dusk"
        else -> "Night"
    }

    fun season(week: Int): String = when {
        week <= 10 -> "winter"
        week <= 18 -> "early_spring"
        week <= 26 -> "breeding"
        week <= 34 -> "post_breeding"
        week <= 44 -> "fall_migration"
        else -> "late_fall"
    }

    /** birdnetlib.utils.return_week_48_from_datetime, on the UTC date. */
    fun week48(now: Instant): Int {
        val date = LocalDate.ofInstant(now, ZoneOffset.UTC)
        val daysInYear = if (date.isLeapYear) 366 else 365
        return ceil((date.dayOfYear.toDouble() / daysInYear) * 48).toInt()
    }

    private fun dayOfYear(now: Instant): Int = LocalDate.ofInstant(now, ZoneOffset.UTC).dayOfYear

    /** Python datetime arithmetic is microsecond-precise; truncate toward zero like timedelta. */
    private fun micros(d: Duration): Long = d.seconds * 1_000_000L + d.nano / 1_000

    /** astral 3.2 sun.py, restricted to what detect.py uses. */
    object Astral {
        class SunError(message: String) : Exception(message)

        data class Sun(val sunrise: Instant, val sunset: Instant)

        private const val SUN_APPARENT_RADIUS = 32.0 / (60.0 * 2.0)
        private const val CIVIL = 6.0
        private const val DEG_TO_RAD = Math.PI / 180.0
        private const val RAD_TO_DEG = 180.0 / Math.PI

        private enum class Direction { RISING, SETTING }

        /** sun(): dawn, sunrise, noon, sunset and dusk are all computed; any failure fails the call. */
        fun sun(date: LocalDate, lat: Double, lon: Double): Sun {
            transitOnDate(date, lat, lon, 90.0 + CIVIL, Direction.RISING, "dawn")
            val sunrise = transitOnDate(date, lat, lon, 90.0 + SUN_APPARENT_RADIUS, Direction.RISING, "sunrise")
            // noon() cannot raise for a finite longitude, so it is not computed here.
            val sunset = transitOnDate(date, lat, lon, 90.0 + SUN_APPARENT_RADIUS, Direction.SETTING, "sunset")
            transitOnDate(date, lat, lon, 90.0 + CIVIL, Direction.SETTING, "dusk")
            return Sun(sunrise, sunset)
        }

        private fun transitOnDate(date: LocalDate, lat: Double, lon: Double, zenith: Double, direction: Direction, what: String): Instant {
            var tot = timeOfTransit(date, lat, lon, zenith, direction)
            var totDate = LocalDate.ofInstant(tot, ZoneOffset.UTC)
            if (totDate != date) {
                val newDate = if (totDate < date) date.plusDays(1) else date.minusDays(1)
                tot = timeOfTransit(newDate, lat, lon, zenith, direction)
                totDate = LocalDate.ofInstant(tot, ZoneOffset.UTC)
                if (totDate != date) throw SunError("Unable to find a $what time on the date specified")
            }
            return tot
        }

        private fun timeOfTransit(date: LocalDate, observerLat: Double, lon: Double, zenith: Double, direction: Direction): Instant {
            val latitude = observerLat.coerceIn(-89.8, 89.8)
            val adjustmentForRefraction = refractionAtZenith(zenith + 0.0)
            val jd = julianDay(date)
            var adjustment = 0.0
            var timeUtc = 0.0
            repeat(2) {
                val jc = (jd + adjustment - 2451545.0) / 36525.0
                val declination = sunDeclination(jc)
                val hourAngle = hourAngle(latitude, declination, zenith + 0.0 + adjustmentForRefraction, direction)
                val delta = -lon - degrees(hourAngle)
                val eqTime = eqOfTime(jc)
                var offset = delta * 4.0 - eqTime
                if (offset < -720.0) offset += 1440
                timeUtc = 720.0 + offset
                adjustment = timeUtc / 1440.0
            }
            return date.atStartOfDay(ZoneOffset.UTC).toInstant().plus(minutesToDuration(timeUtc))
        }

        /** astral minutes_to_timedelta: int() truncation at days, seconds and microseconds. */
        private fun minutesToDuration(input: Double): Duration {
            val days = (input / 1440).toInt()
            var minutes = input - (days * 1440)
            minutes *= 60
            val seconds = minutes.toInt()
            val fraction = minutes - seconds
            val micros = (fraction * 1_000_000).toInt()
            return Duration.ofDays(days.toLong()).plusSeconds(seconds.toLong()).plusNanos(micros * 1_000L)
        }

        fun julianDay(date: LocalDate): Double {
            var year = date.year
            var month = date.monthValue
            if (month <= 2) {
                year -= 1
                month += 12
            }
            val a = (year / 100.0).toInt()
            val b = 2 - a + (a / 4.0).toInt()
            return ((365.25 * (year + 4716)).toInt() + (30.6001 * (month + 1)).toInt() + date.dayOfMonth + 0 + b) - 1524.5
        }

        private fun refractionAtZenith(zenith: Double): Double {
            val elevation = 90 - zenith
            if (elevation >= 85.0) return 0.0
            val te = StrictMath.tan(radians(elevation))
            val correction = when {
                elevation > 5.0 -> 58.1 / te - 0.07 / (te * te * te) + 0.000086 / (te * te * te * te * te)
                elevation > -0.575 -> {
                    val step1 = -12.79 + elevation * 0.711
                    val step2 = 103.4 + elevation * step1
                    val step3 = -518.2 + elevation * step2
                    1735.0 + elevation * step3
                }
                else -> -20.774 / te
            }
            return correction / 3600.0
        }

        private fun hourAngle(latitude: Double, declination: Double, zenith: Double, direction: Direction): Double {
            val latRad = radians(latitude)
            val decRad = radians(declination)
            val zenRad = radians(zenith)
            val h = (StrictMath.cos(zenRad) - StrictMath.sin(latRad) * StrictMath.sin(decRad)) /
                (StrictMath.cos(latRad) * StrictMath.cos(decRad))
            // Python math.acos raises "math domain error" outside [-1, 1].
            if (h > 1.0 || h < -1.0) throw SunError("math domain error")
            val angle = StrictMath.acos(h)
            return if (direction == Direction.SETTING) -angle else angle
        }

        private fun geomMeanLongSun(jc: Double): Double = pyMod(280.46646 + jc * (36000.76983 + 0.0003032 * jc), 360.0)
        private fun geomMeanAnomalySun(jc: Double): Double = 357.52911 + jc * (35999.05029 - 0.0001537 * jc)
        private fun eccentricLocationEarthOrbit(jc: Double): Double = 0.016708634 - jc * (0.000042037 + 0.0000001267 * jc)

        private fun sunEqOfCenter(jc: Double): Double {
            val mrad = radians(geomMeanAnomalySun(jc))
            val sinm = StrictMath.sin(mrad)
            val sin2m = StrictMath.sin(mrad + mrad)
            val sin3m = StrictMath.sin(mrad + mrad + mrad)
            return sinm * (1.914602 - jc * (0.004817 + 0.000014 * jc)) + sin2m * (0.019993 - 0.000101 * jc) + sin3m * 0.000289
        }

        private fun sunTrueLong(jc: Double): Double = geomMeanLongSun(jc) + sunEqOfCenter(jc)

        private fun sunApparentLong(jc: Double): Double {
            val omega = 125.04 - 1934.136 * jc
            return sunTrueLong(jc) - 0.00569 - 0.00478 * StrictMath.sin(radians(omega))
        }

        private fun meanObliquityOfEcliptic(jc: Double): Double {
            val seconds = 21.448 - jc * (46.815 + jc * (0.00059 - jc * (0.001813)))
            return 23.0 + (26.0 + (seconds / 60.0)) / 60.0
        }

        private fun obliquityCorrection(jc: Double): Double {
            val omega = 125.04 - 1934.136 * jc
            return meanObliquityOfEcliptic(jc) + 0.00256 * StrictMath.cos(radians(omega))
        }

        private fun sunDeclination(jc: Double): Double {
            val sint = StrictMath.sin(radians(obliquityCorrection(jc))) * StrictMath.sin(radians(sunApparentLong(jc)))
            return degrees(StrictMath.asin(sint))
        }

        private fun eqOfTime(jc: Double): Double {
            val l0 = geomMeanLongSun(jc)
            val e = eccentricLocationEarthOrbit(jc)
            val m = geomMeanAnomalySun(jc)
            val t = StrictMath.tan(radians(obliquityCorrection(jc)) / 2.0)
            val y = t * t
            val sin2l0 = StrictMath.sin(2.0 * radians(l0))
            val sinm = StrictMath.sin(radians(m))
            val cos2l0 = StrictMath.cos(2.0 * radians(l0))
            val sin4l0 = StrictMath.sin(4.0 * radians(l0))
            val sin2m = StrictMath.sin(2.0 * radians(m))
            val etime = y * sin2l0 - 2.0 * e * sinm + 4.0 * e * y * sinm * cos2l0 - 0.5 * y * y * sin4l0 - 1.25 * e * e * sin2m
            return degrees(etime) * 4.0
        }

        private fun radians(x: Double): Double = x * DEG_TO_RAD
        private fun degrees(x: Double): Double = x * RAD_TO_DEG

        /** CPython float_rem: exact fmod, then shifted so the result takes the divisor's sign. */
        private fun pyMod(a: Double, b: Double): Double {
            var r = a.rem(b)
            if (r != 0.0) {
                if ((b < 0) != (r < 0)) r += b
            } else {
                r = Math.copySign(0.0, b)
            }
            return r
        }
    }
}
